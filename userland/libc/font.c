/* ── Binary Loaders (AZF, PSF1, PSF2) ─────────────────────────────────────── */

az_font_t *az_font_load(const char *path)
{
    if (!path || path[0] == '\0') return NULL;

    int fd = open(path, O_RDONLY);
    if (fd < 0) return NULL;

    struct stat st;
    if (fstat(fd, &st) < 0 || st.st_size < 4) {
        close(fd);
        return NULL;
    }

    size_t file_size = (size_t)st.st_size;
    unsigned char header_buf[128];
    ssize_t nread = read(fd, header_buf, sizeof(header_buf));
    if (nread < 4) {
        close(fd);
        return NULL;
    }

    az_font_t *font = NULL;

    /* 1. Check AZF Magic ("AZFN" -> 0x4E465A41) */
    uint32_t magic32 = *(uint32_t *)header_buf;
    if (magic32 == AZF_MAGIC) {
        if (nread < (ssize_t)sizeof(azf_header_t)) {
            close(fd);
            return NULL;
        }
        azf_header_t *hdr = (azf_header_t *)header_buf;
        if (hdr->version != 1 || hdr->glyph_w == 0 || hdr->glyph_h == 0) {
            close(fd);
            return NULL;
        }
        size_t glyph_bytes = (size_t)hdr->num_glyphs * hdr->bytes_per_glyph;
        if (hdr->header_sz + glyph_bytes > file_size) {
            close(fd);
            return NULL;
        }

        unsigned char *data = (unsigned char *)malloc(glyph_bytes);
        if (!data) {
            close(fd);
            return NULL;
        }

        if (lseek(fd, hdr->header_sz, SEEK_SET) < 0 ||
            read(fd, data, glyph_bytes) != (ssize_t)glyph_bytes) {
            free(data);
            close(fd);
            return NULL;
        }

        font = (az_font_t *)calloc(1, sizeof(az_font_t));
        if (!font) {
            free(data);
            close(fd);
            return NULL;
        }

        strncpy(font->name, hdr->family, sizeof(font->name) - 1);
        strncpy(font->style, hdr->style, sizeof(font->style) - 1);
        strncpy(font->path, path, sizeof(font->path) - 1);
        font->glyph_w = hdr->glyph_w;
        font->glyph_h = hdr->glyph_h;
        font->first_char = hdr->first_char;
        font->last_char = hdr->last_char;
        font->num_glyphs = hdr->num_glyphs;
        font->bytes_per_glyph = hdr->bytes_per_glyph;
        font->flags = hdr->flags;
        font->glyph_data = data;
        font->is_heap = true;

        close(fd);
        return font;
    }

    /* 2. Check Linux PSF2 Magic (0x864AB572) */
    if (magic32 == PSF2_MAGIC) {
        if (nread < (ssize_t)sizeof(psf2_header_t)) {
            close(fd);
            return NULL;
        }
        psf2_header_t *hdr = (psf2_header_t *)header_buf;
        size_t glyph_bytes = (size_t)hdr->length * hdr->charsize;
        if (hdr->headersize + glyph_bytes > file_size) {
            close(fd);
            return NULL;
        }

        unsigned char *data = (unsigned char *)malloc(glyph_bytes);
        if (!data) {
            close(fd);
            return NULL;
        }

        if (lseek(fd, hdr->headersize, SEEK_SET) < 0 ||
            read(fd, data, glyph_bytes) != (ssize_t)glyph_bytes) {
            free(data);
            close(fd);
            return NULL;
        }

        font = (az_font_t *)calloc(1, sizeof(az_font_t));
        if (!font) {
            free(data);
            close(fd);
            return NULL;
        }

        const char *base = strrchr(path, '/');
        base = base ? base + 1 : path;
        strncpy(font->name, base, sizeof(font->name) - 1);
        char *dot = strrchr(font->name, '.');
        if (dot) *dot = '\0';

        strcpy(font->style, "Regular");
        strncpy(font->path, path, sizeof(font->path) - 1);
        font->glyph_w = (uint8_t)hdr->width;
        font->glyph_h = (uint8_t)hdr->height;
        font->first_char = 0;
        font->last_char = (hdr->length > 256) ? 255 : (uint8_t)(hdr->length - 1);
        font->num_glyphs = (uint16_t)hdr->length;
        font->bytes_per_glyph = (uint16_t)hdr->charsize;
        font->flags = AZF_FLAG_MONO;
        font->glyph_data = data;
        font->is_heap = true;

        close(fd);
        return font;
    }

    /* 3. Check Linux PSF1 Magic (0x0436) */
    uint16_t magic16 = *(uint16_t *)header_buf;
    if (magic16 == PSF1_MAGIC) {
        psf1_header_t *hdr = (psf1_header_t *)header_buf;
        uint16_t count = (hdr->mode & PSF1_MODE512) ? 512 : 256;
        size_t glyph_bytes = (size_t)count * hdr->charsize;
        if (sizeof(psf1_header_t) + glyph_bytes > file_size) {
            close(fd);
            return NULL;
        }

        unsigned char *data = (unsigned char *)malloc(glyph_bytes);
        if (!data) {
            close(fd);
            return NULL;
        }

        if (lseek(fd, sizeof(psf1_header_t), SEEK_SET) < 0 ||
            read(fd, data, glyph_bytes) != (ssize_t)glyph_bytes) {
            free(data);
            close(fd);
            return NULL;
        }

        font = (az_font_t *)calloc(1, sizeof(az_font_t));
        if (!font) {
            free(data);
            close(fd);
            return NULL;
        }

        const char *base = strrchr(path, '/');
        base = base ? base + 1 : path;
        strncpy(font->name, base, sizeof(font->name) - 1);
        char *dot = strrchr(font->name, '.');
        if (dot) *dot = '\0';

        strcpy(font->style, "Regular");
        strncpy(font->path, path, sizeof(font->path) - 1);
        font->glyph_w = 8;
        font->glyph_h = hdr->charsize;
        font->first_char = 0;
        font->last_char = (count > 256) ? 255 : (uint8_t)(count - 1);
        font->num_glyphs = count;
        font->bytes_per_glyph = hdr->charsize;
        font->flags = AZF_FLAG_MONO;
        font->glyph_data = data;
        font->is_heap = true;

        close(fd);
        return font;
    }

    close(fd);
    return NULL;
}

void az_font_free(az_font_t *font)
{
    if (!font || !font->is_heap) return;
    if (font->glyph_data) {
        free((void *)font->glyph_data);
        font->glyph_data = NULL;
    }
    free(font);
}

/* ── Default / Active Font Selection ──────────────────────────────────────── */

static int read_conf_value(const char *filepath, const char *key, char *out_val, size_t max_len)
{
    int fd = open(filepath, O_RDONLY);
    if (fd < 0) return -1;

    char buf[512];
    ssize_t n = read(fd, buf, sizeof(buf) - 1);
    close(fd);
    if (n <= 0) return -1;
    buf[n] = '\0';

    char *line = strtok(buf, "\r\n");
    while (line) {
        while (*line == ' ' || *line == '\t') line++;
        if (*line != '#' && *line != '[') {
            char *eq = strchr(line, '=');
            if (eq) {
                *eq = '\0';
                char *k = line;
                char *v = eq + 1;
                while (*v == ' ' || *v == '\t') v++;
                /* Trim trailing */
                char *end_k = k + strlen(k) - 1;
                while (end_k > k && (*end_k == ' ' || *end_k == '\t')) *end_k-- = '\0';
                char *end_v = v + strlen(v) - 1;
                while (end_v >= v && (*end_v == ' ' || *end_v == '\t' || *end_v == '\r')) *end_v-- = '\0';

                if (strcmp(k, key) == 0 || strcmp(k, "font") == 0 || strcmp(k, "system_font") == 0) {
                    strncpy(out_val, v, max_len - 1);
                    out_val[max_len - 1] = '\0';
                    return 0;
                }
            }
        }
        line = strtok(NULL, "\r\n");
    }
    return -1;
}

az_font_t *az_font_load_default(void)
{
    char font_path[128] = {0};

    /* 1. Check persistent SATA config first */
    if (read_conf_value(AZ_FONT_CONFIG_HDD, "system_font", font_path, sizeof(font_path)) == 0) {
        az_font_t *f = az_font_load(font_path);
        if (f) return f;
    }

    /* 2. Check system rootfs config */
    if (read_conf_value(AZ_FONT_CONFIG_FILE, "system_font", font_path, sizeof(font_path)) == 0) {
        az_font_t *f = az_font_load(font_path);
        if (f) return f;
    }

    /* 3. Try standard system default fonts on drive */
    az_font_t *f = az_font_load(AZ_FONT_DIR_SYSTEM "/vga_regular.azf");
    if (f) return f;

    f = az_font_load(AZ_FONT_DIR_SYSTEM "/default.azf");
    if (f) return f;

    f = az_font_load(AZ_FONT_DIR_SYSTEM "/terminus_regular.azf");
    if (f) return f;

    /* 4. Fallback to embedded static table */
    return (az_font_t *)&s_builtin_font_regular;
}

az_font_t *az_font_load_by_name(const char *name)
{
    if (!name || name[0] == '\0') return az_font_load_default();

    char path[256];

    /* Direct path check */
    if (strchr(name, '/')) {
        az_font_t *f = az_font_load(name);
        if (f) return f;
    }

    /* Check system fonts dir: /usr/share/fonts/<name>.azf */
    snprintf(path, sizeof(path), "%s/%s.azf", AZ_FONT_DIR_SYSTEM, name);
    az_font_t *f = az_font_load(path);
    if (f) return f;

    snprintf(path, sizeof(path), "%s/%s", AZ_FONT_DIR_SYSTEM, name);
    f = az_font_load(path);
    if (f) return f;

    /* Check persistent drive: /hdd/fonts/<name>.azf */
    snprintf(path, sizeof(path), "%s/%s.azf", AZ_FONT_DIR_PERSISTENT, name);
    f = az_font_load(path);
    if (f) return f;

    snprintf(path, sizeof(path), "%s/%s", AZ_FONT_DIR_PERSISTENT, name);
    f = az_font_load(path);
    if (f) return f;

    /* Scan directories for matching family name */
    az_font_info_t list[32];
    int count = az_font_scan_dirs(list, 32);
    for (int i = 0; i < count; i++) {
        if (strcasecmp(list[i].name, name) == 0) {
            f = az_font_load(list[i].path);
            if (f) return f;
        }
    }

    return az_font_load_default();
}

int az_font_set_default_font(const char *font_path)
{
    if (!font_path) return -1;

    char conf_data[256];
    snprintf(conf_data, sizeof(conf_data),
             "[font]\nsystem_font=%s\nmono_font=%s\nsize=16\n",
             font_path, font_path);

    /* Write to /hdd/etc/font.conf if persistent drive is present */
    struct stat st;
    if (stat("/hdd", &st) == 0 && S_ISDIR(st.st_mode)) {
        mkdir("/hdd/etc", 0755);
        int fd = open(AZ_FONT_CONFIG_HDD, O_WRONLY | O_CREAT | O_TRUNC, 0644);
        if (fd >= 0) {
            write(fd, conf_data, strlen(conf_data));
            close(fd);
        }
    }

    /* Write to /etc/font.conf */
    int fd = open(AZ_FONT_CONFIG_FILE, O_WRONLY | O_CREAT | O_TRUNC, 0644);
    if (fd >= 0) {
        write(fd, conf_data, strlen(conf_data));
        close(fd);
    }

    return 0;
}

/* ── Directory Discovery ──────────────────────────────────────────────────── */

static void inspect_and_add_font(const char *dirpath, const char *filename,
                                 az_font_info_t *out_list, int *count, int max_fonts)
{
    if (*count >= max_fonts) return;

    /* Only inspect .azf, .psf, .psfu files */
    const char *ext = strrchr(filename, '.');
    if (!ext) return;
    if (strcmp(ext, ".azf") != 0 && strcmp(ext, ".psf") != 0 && strcmp(ext, ".psfu") != 0) return;

    char fullpath[256];
    snprintf(fullpath, sizeof(fullpath), "%s/%s", dirpath, filename);

    az_font_t *f = az_font_load(fullpath);
    if (!f) return;

    az_font_info_t *info = &out_list[*count];
    strncpy(info->name, f->name, sizeof(info->name) - 1);
    strncpy(info->style, f->style, sizeof(info->style) - 1);
    strncpy(info->path, fullpath, sizeof(info->path) - 1);
    info->glyph_w = f->glyph_w;
    info->glyph_h = f->glyph_h;
    info->flags = f->flags;

    struct stat st;
    if (stat(fullpath, &st) == 0) info->file_size = (size_t)st.st_size;
    else info->file_size = 0;

    (*count)++;
    az_font_free(f);
}

static void scan_directory(const char *dirpath, az_font_info_t *out_list, int *count, int max_fonts)
{
    DIR *dir = opendir(dirpath);
    if (!dir) return;

    struct dirent *ent;
    while ((ent = readdir(dir)) != NULL) {
        if (ent->d_name[0] == '.') continue;
        inspect_and_add_font(dirpath, ent->d_name, out_list, count, max_fonts);
    }
    closedir(dir);
}

int az_font_scan_dirs(az_font_info_t *out_list, int max_fonts)
{
    if (!out_list || max_fonts <= 0) return 0;
    int count = 0;

    /* Scan system root drive first */
    scan_directory(AZ_FONT_DIR_SYSTEM, out_list, &count, max_fonts);

    /* Scan persistent SATA drive */
    scan_directory(AZ_FONT_DIR_PERSISTENT, out_list, &count, max_fonts);

    return count;
}

/* ── Glyph Rendering & Rasterization ──────────────────────────────────────── */

const unsigned char *az_font_get_glyph(const az_font_t *font, int c)
{
    if (!font) font = &s_builtin_font_regular;
    unsigned char uc = (unsigned char)c;

    if (uc < font->first_char || uc > font->last_char) {
        uc = font->first_char;
    }

    size_t idx = (size_t)(uc - font->first_char);
    if (idx >= font->num_glyphs) idx = 0;

    return font->glyph_data + idx * font->bytes_per_glyph;
}

void az_font_draw_char(
    uint32_t *buf, uint32_t pitch_px,
    uint32_t buf_w, uint32_t buf_h,
    int px, int py, char c, uint32_t color,
    const az_font_t *font, int scale, bool bold)
{
    if (!buf || buf_w == 0 || buf_h == 0) return;
    if (!font) font = &s_builtin_font_regular;
    if (scale < 1) scale = 1;

    int gw = font->glyph_w;
    int gh = font->glyph_h;
    int dw = gw * scale;
    int dh = gh * scale;

    /* Complete quick rejection if offscreen */
    if (px + dw <= 0 || py + dh <= 0 || px >= (int)buf_w || py >= (int)buf_h) return;

    const unsigned char *glyph = az_font_get_glyph(font, (unsigned char)c);
    int row_stride = (gw + 7) / 8;

    /* Fast path: fully in bounds */
    if (px >= 0 && py >= 0 && (unsigned int)(px + dw) <= buf_w && (unsigned int)(py + dh) <= buf_h) {
        uint32_t *dst_base = buf + (unsigned int)py * pitch_px + (unsigned int)px;
        for (int r = 0; r < gh; r++, dst_base += (size_t)scale * pitch_px) {
            unsigned char bits = glyph[r * row_stride];
            if (bold) bits |= (unsigned char)(bits >> 1);
            if (!bits) continue;

            for (int b = 0; b < gw; b++) {
                if (!(bits & (0x80 >> b))) continue;
                unsigned int fx = (unsigned int)b * scale;
                for (int sy = 0; sy < scale; sy++) {
                    uint32_t *drow = dst_base + (size_t)sy * pitch_px;
                    for (int sx = 0; sx < scale; sx++) {
                        drow[fx + sx] = color;
                    }
                }
            }
        }
        return;
    }

    /* Clipped path */
    for (int r = 0; r < gh; r++) {
        unsigned char bits = glyph[r * row_stride];
        if (bold) bits |= (unsigned char)(bits >> 1);
        if (!bits) continue;

        for (int b = 0; b < gw; b++) {
            if (!(bits & (0x80 >> b))) continue;
            for (int sy = 0; sy < scale; sy++) {
                int fy = py + r * scale + sy;
                if (fy < 0 || (unsigned int)fy >= buf_h) continue;
                for (int sx = 0; sx < scale; sx++) {
                    int fx = px + b * scale + sx;
                    if (fx < 0 || (unsigned int)fx >= buf_w) continue;
                    buf[(unsigned int)fy * pitch_px + (unsigned int)fx] = color;
                }
            }
        }
    }
}

void az_font_draw_str(
    uint32_t *buf, uint32_t pitch_px,
    uint32_t buf_w, uint32_t buf_h,
    int px, int py, const char *s, uint32_t color,
    const az_font_t *font, int scale, bool bold)
{
    if (!buf || !s) return;
    if (!font) font = &s_builtin_font_regular;
    if (scale < 1) scale = 1;

    int orig_x = px;
    int advance = font->glyph_w * scale;
    int line_h = font->glyph_h * scale;

    for (int i = 0; s[i]; i++) {
        if (s[i] == '\n') {
            py += line_h;
            px = orig_x;
            continue;
        }
        if (s[i] == '\r') continue;
        az_font_draw_char(buf, pitch_px, buf_w, buf_h, px, py, s[i], color, font, scale, bold);
        px += advance;
    }
}

int az_font_str_width(const az_font_t *font, const char *s, int scale)
{
    if (!s) return 0;
    if (!font) font = &s_builtin_font_regular;
    if (scale < 1) scale = 1;

    int max_w = 0;
    int cur_w = 0;
    int advance = font->glyph_w * scale;

    for (int i = 0; s[i]; i++) {
        if (s[i] == '\n') {
            if (cur_w > max_w) max_w = cur_w;
            cur_w = 0;
        } else if (s[i] != '\r') {
            cur_w += advance;
        }
    }
    if (cur_w > max_w) max_w = cur_w;
    return max_w;
}
