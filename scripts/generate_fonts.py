def main():
    root_dir = os.path.dirname(os.path.dirname(os.path.abspath(__file__)))
    build_fonts_dir = os.path.join(root_dir, 'userland', 'build', 'usr', 'share', 'fonts')
    hdd_fonts_dir = os.path.join(root_dir, 'hdd_root', 'fonts')

    os.makedirs(build_fonts_dir, exist_ok=True)
    os.makedirs(hdd_fonts_dir, exist_ok=True)

    print(f"Generating AzamiOS binary fonts...")

    fonts = [
        ("vga_regular.azf", "VGA", "Regular", 8, 16, VGA_8X16, AZF_FLAG_MONO),
        ("vga_small.azf", "VGA", "Small", 8, 8, derive_vga_small(), AZF_FLAG_MONO),
        ("terminus_regular.azf", "Terminus", "Regular", 8, 16, derive_terminus_regular(), AZF_FLAG_MONO),
        ("terminus_bold.azf", "Terminus", "Bold", 8, 16, derive_bold(derive_terminus_regular()), AZF_FLAG_MONO | AZF_FLAG_BOLD),
        ("modern_sans.azf", "Modern Sans", "Regular", 8, 16, derive_modern_sans(), 0),
        ("cozy_serif.azf", "Cozy Serif", "Regular", 8, 16, derive_cozy_serif(), AZF_FLAG_SERIF),
    ]

    for fname, fam, sty, w, h, glyphs, flg in fonts:
        blob = make_azf_binary(fam, sty, w, h, glyphs, flg)
        dst = os.path.join(build_fonts_dir, fname)
        with open(dst, 'wb') as f:
            f.write(blob)
        print(f"  -> Built {fname} ({fam} {sty}, {w}x{h}, {len(blob)} bytes)")

    # Create default.azf as a copy of vga_regular.azf
    vga_blob = make_azf_binary("VGA", "Regular", 8, 16, VGA_8X16, AZF_FLAG_MONO)
    with open(os.path.join(build_fonts_dir, "default.azf"), 'wb') as f:
        f.write(vga_blob)

    # Place persistent fonts on /hdd/fonts
    sample_blob = make_azf_binary("Terminus Custom", "Regular", 8, 16, derive_terminus_regular(), AZF_FLAG_MONO)
    with open(os.path.join(hdd_fonts_dir, "custom_sample.azf"), 'wb') as f:
        f.write(sample_blob)
    print(f"  -> Built hdd_root/fonts/custom_sample.azf")

    # Write README on persistent hard drive explaining user font installation
    readme_path = os.path.join(hdd_fonts_dir, "README.txt")
    with open(readme_path, 'w') as f:
        f.write("""AzamiOS Persistent Font Storage (/hdd/fonts)
=============================================
You can store custom fonts on this drive!

Supported formats:
  - Native Azami Font (.azf)
  - Linux PC Screen Font (.psf, .psf2, .psfu)

How to use:
  1. Copy your .azf or .psf font file to /hdd/fonts/
  2. List available fonts:
     setfont -l
  3. Preview the font:
     setfont -p /hdd/fonts/custom_sample.azf
  4. Set as system default font:
     setfont /hdd/fonts/custom_sample.azf
""")
    print(f"  -> Written hdd_root/fonts/README.txt")
    print("Font compilation complete.")

if __name__ == '__main__':
    main()
