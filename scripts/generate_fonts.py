def make_azf_binary(family, style, glyph_w, glyph_h, glyphs, flags=AZF_FLAG_MONO):
    first_char = 0x20
    last_char = 0x20 + len(glyphs) - 1
    num_glyphs = len(glyphs)
    row_bytes = (glyph_w + 7) // 8
    bytes_per_glyph = glyph_h * row_bytes

    fam_b = family.encode('utf-8')[:31].ljust(32, b'\x00')
    sty_b = style.encode('utf-8')[:15].ljust(16, b'\x00')

    # Header layout:
    # uint32 magic (4)
    # uint16 version (2)
    # uint16 header_sz (2)
    # char family[32] (32)
    # char style[16] (16)
    # uint8 glyph_w (1)
    # uint8 glyph_h (1)
    # uint8 first_char (1)
    # uint8 last_char (1)
    # uint16 num_glyphs (2)
    # uint16 bytes_per_glyph (2)
    # uint32 flags (4)
    # Total = 68 bytes
    header = struct.pack(
        '<IHH32s16sBBBBHHI',
        AZF_MAGIC,
        AZF_VERSION,
        AZF_HEADER_SZ,
        fam_b,
        sty_b,
        glyph_w,
        glyph_h,
        first_char,
        last_char,
        num_glyphs,
        bytes_per_glyph,
        flags
    )

    data = bytearray(header)
    for g in glyphs:
        for r in g:
            data.append(r)

    return bytes(data)

